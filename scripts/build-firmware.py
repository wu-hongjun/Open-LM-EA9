#!/usr/bin/env python3
"""Pinned release build; bootstrap official dependencies only when absent."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tarfile
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--variant", choices=("metadata", "upstream-af", "reconciled-af"), default="metadata")
variant = parser.parse_args().variant
if variant == "upstream-af":
    # Preserve the installed 2.1.0 journal/image. Current source builds 2.2.0.
    legacy = ROOT / "apps/macos/Sources/DeviceKit/Resources/ea9-af-template.bin"
    data = legacy.read_bytes()
    if len(data) != 0x5100 or hashlib.sha256(data).hexdigest() != "6e48fcdd48df13ec529badd4626ee99120e005e4cd011ad664c683720b006552":
        raise SystemExit("Frozen 2.1.0 template failed length/digest verification; no resource was changed.")
    print("Verified frozen upstream-AF 2.1.0 template; use --variant reconciled-af to build current source.")
    raise SystemExit(0)
DEPS = ROOT / "tools/firmware-deps"
DEPS.mkdir(parents=True, exist_ok=True)
records = json.loads((ROOT / "firmware/dependencies.json").read_text())
destinations = {
    "arm": DEPS / "arm-gnu-toolchain-14.2.rel1-darwin-arm64-arm-none-eabi",
    "dfp": DEPS / "samd21-dfp-2",
    "cmsis": DEPS / "CMSIS_5-5.9.0",
}
for name, record in records.items():
    archive_name = "CMSIS_5-5.9.0.tar.gz" if name == "cmsis" else record["url"].rsplit("/", 1)[-1]
    archive = DEPS / archive_name
    if not archive.exists():
        with urllib.request.urlopen(record["url"], timeout=60) as response, archive.open("wb") as output:
            shutil.copyfileobj(response, output)
    assert archive.stat().st_size == record["bytes"], f"Dependency size mismatch: {name}"
    assert hashlib.sha256(archive.read_bytes()).hexdigest() == record["sha256"], f"Dependency checksum mismatch: {name}"
    if not destinations[name].exists():
        if name == "dfp":
            with zipfile.ZipFile(archive) as package:
                package.extractall(destinations[name])
        else:
            with tarfile.open(archive) as package:
                package.extractall(DEPS, filter="data")
subprocess.run(["make", "-C", str(ROOT / "firmware/ea9"),
                "reconciled-af" if variant == "reconciled-af" else "all"], check=True)
binary = ROOT / ("firmware/ea9/build/reconciled/ea9-af-reconciled-template.bin" if variant == "reconciled-af"
                 else "firmware/ea9/build/ea9-profile-template.bin")
data = binary.read_bytes()
expected_bytes = 0x5000 if variant == "reconciled-af" else 0x5100
if len(data) != expected_bytes or data[-256:] != bytes(256):
    raise SystemExit("Unexpected template span/profile row; resources were not changed.")
sha = hashlib.sha256(data).hexdigest()
if variant == "metadata":
    resource = ROOT / "apps/macos/Sources/DeviceKit/Resources/ea9-profile-template.bin"
    resource.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(binary, resource)
    (resource.parent.parent / "TrustedTemplate.swift").write_text(
        '// Generated by scripts/build-firmware.py; pinned application template.\n'
        f'enum TrustedTemplate {{ static let sha256 = "{sha}" }}\n'
    )
else:
    resource = ROOT / "apps/macos/Sources/DeviceKit/Resources/ea9-af-reconciled-template.bin"
    shutil.copyfile(binary, resource)
    (resource.parent.parent / "TrustedReconciledAFTemplate.swift").write_text(
        '// Generated by scripts/build-firmware.py; reconciled AF 2.2.0 template.\n'
        f'enum TrustedReconciledAFTemplate {{ static let sha256 = "{sha}" }}\n'
    )
    sources = sorted((ROOT / "firmware/ea9/src").rglob("*")) + [ROOT / "firmware/ea9/Makefile"]
    manifest = {
        "variant": variant, "status": "offline-candidate-not-camera-qualified",
        "templateSHA256": sha, "bytes": len(data), "applicationOrigin": 0x5000,
        "profileAddress": 0x9f00, "profileBytes": 256, "applicationEnd": 0xa000, "cameraVersionBCD": "0x22",
        "proposedLoaderVersion": [2, 2, 0], "motorMotionEnabled": True,
        "diagnosticFlashWritesEnabled": False, "cameraQualified": False,
        "hardwareReportsSentByBuild": 0, "dependencies": records,
        "sources": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in sources if p.is_file()},
    }
    binary.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
print(f"{variant} template: {len(data)} bytes, SHA-256 {sha}")
